-- ======================= PART 1: SCHEMA =====================================
DROP TABLE IF EXISTS business_setting    CASCADE;
DROP TABLE IF EXISTS inventory_count     CASCADE;
DROP TABLE IF EXISTS inventory_adjustment CASCADE;
DROP TABLE IF EXISTS sale_item           CASCADE;
DROP TABLE IF EXISTS sale                CASCADE;
DROP TABLE IF EXISTS production_batch    CASCADE;
DROP TABLE IF EXISTS customer            CASCADE;
DROP TABLE IF EXISTS tax_code            CASCADE;
DROP TABLE IF EXISTS sales_channel       CASCADE;
DROP TABLE IF EXISTS product             CASCADE;

CREATE TABLE product (
    product_id       SERIAL PRIMARY KEY,
    product_code     VARCHAR(4)  NOT NULL UNIQUE,
    product_name     VARCHAR(50) NOT NULL,
    retail_price     NUMERIC(6,2) NOT NULL,
    wholesale_price  NUMERIC(6,2) NOT NULL,
    unit_cost        NUMERIC(6,2) NOT NULL,
    reorder_level    INT NOT NULL,
    is_cobranded     BOOLEAN NOT NULL,
    scholarship_rate NUMERIC(4,3) NOT NULL,
    -- BBQ sauce sold in jars is "qualifying food" under NC law: it is taxed at the
    -- reduced 2% food rate, not the general rate (matches Dr. D's own records)
    is_qualifying_food BOOLEAN NOT NULL DEFAULT TRUE,
    -- production planning: days from ordering a batch to having jars, plus a safety buffer
    lead_time_days   INT NOT NULL DEFAULT 14 CHECK (lead_time_days > 0),
    safety_days      INT NOT NULL DEFAULT 7  CHECK (safety_days >= 0)
);

CREATE TABLE sales_channel (
    channel_id   SERIAL PRIMARY KEY,
    channel_name VARCHAR(20) NOT NULL UNIQUE,
    is_taxable   BOOLEAN NOT NULL,
    -- card-processing fee charged automatically on this channel (Shopify: 2.9% + $0.30
    -- of the order total). 0 = no automatic fee; the owner can enter the actual fee.
    fee_pct      NUMERIC(5,4) NOT NULL DEFAULT 0,
    fee_fixed    NUMERIC(6,2) NOT NULL DEFAULT 0,
    -- which product price this channel charges by default, and whether orders ship
    price_basis  VARCHAR(10)  NOT NULL DEFAULT 'retail' CHECK (price_basis IN ('retail','wholesale','free')),
    ships_orders BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE tax_code (                              -- Function 1 (teammate's tax dataset)
    tax_code  VARCHAR(10) PRIMARY KEY,               -- state '-' county FIPS, e.g. NC-183 (Wake)
    state     VARCHAR(2)  NOT NULL,
    county    VARCHAR(60) NOT NULL,
    fips_code VARCHAR(5)  NOT NULL,
    tax_rate  NUMERIC(6,4),                          -- rate CHARGED on new sales; NULL when 'Review Required'
    status    VARCHAR(20) NOT NULL,                  -- Provisional / Review Required / Refreshed / Verified
    food_rate NUMERIC(6,4),                          -- rate charged on qualifying FOOD (the sauce). Set only
                                                     -- where the business collects tax (NC = 2%); NULL = not
                                                     -- collected there (out-of-state order, no registration)
    -- rate history, so the owner can always see where a rate came from:
    lookup_rate    NUMERIC(6,4),                     -- Function 1's original estimate (never overwritten)
    effective_date DATE,                             -- date the charged rate took effect (from the rate file)
    rate_source    VARCHAR(250),                     -- Function 1 file / official rate-file URL / tax_rates.csv
    last_refreshed TIMESTAMP                         -- when the dashboard last refreshed this county
);
-- Status meanings:
--   Provisional     = Function 1 estimate (state + county rate only)
--   Review Required = Function 1 could not determine one rate -> cannot be used for sales
--   Refreshed       = updated from the latest NC rate file, incl. local transit / special-district taxes
--   Verified        = checked by hand against NCDOR (tax_rates/tax_rates.csv)
--   State only      = "County not listed" row for out-of-state orders (not Function 1 data)
-- tax_rate is the GENERAL rate (non-food items). The sauce uses food_rate.

CREATE TABLE customer (
    customer_id   SERIAL PRIMARY KEY,
    customer_name VARCHAR(60) NOT NULL,
    customer_type VARCHAR(20) NOT NULL
);

CREATE TABLE production_batch (
    batch_id      SERIAL PRIMARY KEY,
    product_id    INT NOT NULL REFERENCES product(product_id),
    batch_code    VARCHAR(20) NOT NULL UNIQUE,
    produced_date DATE NOT NULL,
    jars_produced INT NOT NULL CHECK (jars_produced > 0),
    unit_cost     NUMERIC(6,2) NOT NULL
);

CREATE TABLE sale (
    sale_id          SERIAL PRIMARY KEY,
    sale_date        DATE NOT NULL,
    channel_id       INT  NOT NULL REFERENCES sales_channel(channel_id),
    customer_id      INT  REFERENCES customer(customer_id),
    tax_code         VARCHAR(10) REFERENCES tax_code(tax_code),
    invoice_ref      VARCHAR(40),
    item_charge      NUMERIC(12,2) NOT NULL DEFAULT 0,
    shipping_revenue NUMERIC(12,2) NOT NULL DEFAULT 0,
    shopify_fees     NUMERIC(12,2) NOT NULL DEFAULT 0,
    shipping_expense NUMERIC(12,2) NOT NULL DEFAULT 0,
    product_cost     NUMERIC(12,2) NOT NULL DEFAULT 0,
    state_tax        NUMERIC(12,2) NOT NULL DEFAULT 0,
    scholarship      NUMERIC(12,2) NOT NULL DEFAULT 0,
    gross_profit     NUMERIC(12,2) GENERATED ALWAYS AS
        (item_charge + shipping_revenue - shopify_fees - shipping_expense - product_cost - scholarship) STORED
);

CREATE TABLE sale_item (
    sale_item_id SERIAL PRIMARY KEY,
    sale_id      INT NOT NULL REFERENCES sale(sale_id),
    product_id   INT NOT NULL REFERENCES product(product_id),
    quantity     INT NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC(12,6) NOT NULL CHECK (unit_price >= 0)
);

-- signed stock corrections outside of sales: breakage, spoilage, samples, count fixes
CREATE TABLE inventory_adjustment (
    adjustment_id SERIAL PRIMARY KEY,
    product_id    INT NOT NULL REFERENCES product(product_id),
    adj_date      DATE NOT NULL,
    quantity      INT NOT NULL,                 -- negative = loss, positive = gain
    reason        VARCHAR(30) NOT NULL,
    note          VARCHAR(120)
);

-- physical shelf counts, for reconciliation against the system number
CREATE TABLE inventory_count (
    count_id     SERIAL PRIMARY KEY,
    product_id   INT NOT NULL REFERENCES product(product_id),
    count_date   DATE NOT NULL,
    counted_jars INT NOT NULL CHECK (counted_jars >= 0),
    note         VARCHAR(120)
);

-- business-wide settings: the app and the views read these instead of hard-coding them
CREATE TABLE business_setting (
    setting_key   VARCHAR(40)  PRIMARY KEY,
    setting_value VARCHAR(300) NOT NULL,
    description   VARCHAR(200) NOT NULL
);

