-- ======================= PART 6: SINGLE SOURCE OF MONEY MATH =================
-- The app writes only what the owner knows (lines, shipping charged/paid, and a
-- card fee if he has one); this function derives every other money field.
CREATE OR REPLACE FUNCTION fn_finalize_sale(p_sale_id INT) RETURNS void AS $$
BEGIN
    -- 1. revenue, product cost and the NC State scholarship from the line items
    --    (scholarship = each product's rate x the revenue ACTUALLY received)
    UPDATE sale s SET
        item_charge  = COALESCE(a.rev,0),
        product_cost = COALESCE(a.cost,0),
        scholarship  = ROUND(COALESCE(a.sch,0), 2)
    FROM (SELECT SUM(si.quantity*si.unit_price)                    AS rev,
                 SUM(si.quantity*p.unit_cost)                      AS cost,
                 SUM(si.quantity*si.unit_price*p.scholarship_rate) AS sch
          FROM sale_item si JOIN product p ON p.product_id=si.product_id
          WHERE si.sale_id=p_sale_id) a
    WHERE s.sale_id=p_sale_id;

    -- 2. sales tax on (items + shipping charged). Qualifying food -> the county's
    --    food rate (NC: 2%); anything else -> the general rate. No food_rate means
    --    the business doesn't collect in that state (out-of-state order) -> $0.
    UPDATE sale s SET
        state_tax = CASE WHEN NOT sc.is_taxable OR t.food_rate IS NULL THEN 0
                         ELSE ROUND((s.item_charge + s.shipping_revenue)
                                    * CASE WHEN f.all_food THEN t.food_rate
                                           ELSE COALESCE(t.tax_rate,0) END, 2) END
    FROM sales_channel sc, tax_code t,
         (SELECT COALESCE(bool_and(p.is_qualifying_food), TRUE) AS all_food
          FROM sale_item si JOIN product p ON p.product_id=si.product_id
          WHERE si.sale_id=p_sale_id) f
    WHERE sc.channel_id=s.channel_id AND t.tax_code=s.tax_code AND s.sale_id=p_sale_id;

    -- 3. card-processing fee: automatic where the channel has a fee schedule
    --    (Shopify 2.9% + $0.30 of the order total, as on Dr. D's statements);
    --    otherwise keep the fee the owner entered (e.g. market card reader payout).
    UPDATE sale s SET
        shopify_fees = CASE WHEN sc.fee_pct > 0 OR sc.fee_fixed > 0
                            THEN ROUND(sc.fee_pct*(s.item_charge + s.shipping_revenue + s.state_tax)
                                       + sc.fee_fixed, 2)
                            ELSE s.shopify_fees END
    FROM sales_channel sc
    WHERE sc.channel_id=s.channel_id AND s.sale_id=p_sale_id;
END; $$ LANGUAGE plpgsql;

-- Seed shipping on online orders FIRST (customers pay $6-17, the label costs
-- $5-13), so the function below can tax it and compute the Shopify fee.
UPDATE sale s SET
    shipping_revenue = CASE WHEN sc.channel_name='Shopify' THEN (floor(random()*12)+6)::numeric ELSE 0 END,
    shipping_expense = CASE WHEN sc.channel_name='Shopify' THEN ROUND((random()*8+5)::numeric,2) ELSE 0 END
FROM sales_channel sc WHERE sc.channel_id=s.channel_id;

