-- ======================= PART 7: MANAGEMENT VIEWS ===========================
-- True on-hand = produced + adjustments - sold
CREATE OR REPLACE VIEW v_inventory_on_hand AS
SELECT p.product_id, p.product_code, p.product_name,
       COALESCE(b.produced,0) AS total_produced,
       COALESCE(j.adj,0)      AS total_adjusted,
       COALESCE(x.sold,0)     AS total_sold,
       COALESCE(b.produced,0)+COALESCE(j.adj,0)-COALESCE(x.sold,0) AS on_hand,
       p.reorder_level,
       CASE WHEN COALESCE(b.produced,0)+COALESCE(j.adj,0)-COALESCE(x.sold,0) < p.reorder_level
            THEN 'LOW - REORDER' ELSE 'OK' END AS stock_status
FROM product p
LEFT JOIN (SELECT product_id, SUM(jars_produced) produced FROM production_batch GROUP BY product_id) b ON b.product_id=p.product_id
LEFT JOIN (SELECT product_id, SUM(quantity) adj FROM inventory_adjustment GROUP BY product_id) j ON j.product_id=p.product_id
LEFT JOIN (SELECT product_id, SUM(quantity) sold FROM sale_item GROUP BY product_id) x ON x.product_id=p.product_id;

CREATE OR REPLACE VIEW v_low_stock AS
SELECT * FROM v_inventory_on_hand WHERE stock_status='LOW - REORDER';

CREATE OR REPLACE VIEW v_sales_by_channel AS
SELECT sc.channel_name, SUM(si.quantity) AS units_sold,
       ROUND(SUM(si.quantity*si.unit_price),2) AS revenue
FROM sale_item si JOIN sale s ON s.sale_id=si.sale_id
JOIN sales_channel sc ON sc.channel_id=s.channel_id
GROUP BY sc.channel_name ORDER BY units_sold DESC;

CREATE OR REPLACE VIEW v_monthly_report AS
WITH jars AS (
    SELECT date_trunc('month', s.sale_date) AS mkey, SUM(si.quantity) AS jars_sold
    FROM sale_item si JOIN sale s ON s.sale_id=si.sale_id GROUP BY 1),
monthly_money AS (
    SELECT date_trunc('month', sale_date) AS mkey,
           ROUND(SUM(item_charge),2) AS revenue,
           ROUND(SUM(shopify_fees+shipping_expense+product_cost),2) AS expenses,
           ROUND(SUM(scholarship),2) AS scholarship_owed,
           ROUND(SUM(gross_profit),2) AS gross_profit
    FROM sale GROUP BY 1)
SELECT TO_CHAR(m.mkey,'MM-DD-YYYY') AS month,
       COALESCE(j.jars_sold,0) AS jars_sold, m.revenue, m.expenses, m.scholarship_owed, m.gross_profit
FROM monthly_money m LEFT JOIN jars j ON j.mkey=m.mkey ORDER BY m.mkey;

-- the same months broken down by product (one row per month x product, any number of products)
CREATE OR REPLACE VIEW v_monthly_product AS
SELECT TO_CHAR(date_trunc('month', s.sale_date),'MM-DD-YYYY') AS month,
       p.product_code, p.product_name,
       SUM(si.quantity) AS jars, ROUND(SUM(si.quantity*si.unit_price),2) AS revenue
FROM sale_item si JOIN sale s ON s.sale_id=si.sale_id JOIN product p ON p.product_id=si.product_id
GROUP BY date_trunc('month', s.sale_date), p.product_id, p.product_code, p.product_name
ORDER BY date_trunc('month', s.sale_date), p.product_id;

-- Function 3: the monthly NC State licensing report. Co-branded (SS) bottles and
-- revenue come from the line items; the amount owed comes from the sale headers
-- (aggregated separately so a mixed DD+SS sale is never double counted).
-- The non-co-branded (DD) figures are returned too, as proof they are EXCLUDED:
-- DD has a 0% scholarship rate, so it adds nothing to the amount owed.
CREATE OR REPLACE VIEW v_scholarship_owed AS
WITH lines AS (
    SELECT date_trunc('month', s.sale_date) AS mkey,
           SUM(CASE WHEN p.is_cobranded THEN si.quantity END)                        AS cobranded_jars,
           ROUND(SUM(CASE WHEN p.is_cobranded THEN si.quantity*si.unit_price END),2) AS cobranded_revenue,
           SUM(CASE WHEN NOT p.is_cobranded THEN si.quantity END)                        AS excluded_jars,
           ROUND(SUM(CASE WHEN NOT p.is_cobranded THEN si.quantity*si.unit_price END),2) AS excluded_revenue
    FROM sale_item si JOIN product p ON p.product_id=si.product_id
    JOIN sale s ON s.sale_id=si.sale_id GROUP BY 1),
owed AS (
    SELECT date_trunc('month', sale_date) AS mkey, ROUND(SUM(scholarship),2) AS scholarship_owed
    FROM sale GROUP BY 1)
SELECT TO_CHAR(o.mkey,'MM-DD-YYYY') AS month,
       COALESCE(l.cobranded_jars,0) AS cobranded_jars, COALESCE(l.cobranded_revenue,0) AS cobranded_revenue,
       o.scholarship_owed,
       COALESCE(l.excluded_jars,0) AS excluded_jars, COALESCE(l.excluded_revenue,0) AS excluded_revenue
FROM owed o LEFT JOIN lines l ON l.mkey=o.mkey
ORDER BY o.mkey;

-- Every stock movement, chronological: production in, sales out, adjustments
CREATE OR REPLACE VIEW v_inventory_ledger AS
SELECT b.produced_date AS movement_date, p.product_code, 'PRODUCTION' AS movement_type,
       b.jars_produced AS quantity_change, b.batch_code AS reference
FROM production_batch b JOIN product p ON p.product_id=b.product_id
UNION ALL
SELECT s.sale_date, p.product_code, 'SALE', -si.quantity, s.invoice_ref
FROM sale_item si JOIN sale s ON s.sale_id=si.sale_id JOIN product p ON p.product_id=si.product_id
UNION ALL
SELECT a.adj_date, p.product_code, 'ADJUSTMENT', a.quantity, a.reason
FROM inventory_adjustment a JOIN product p ON p.product_id=a.product_id;

-- Physical-count reconciliation: latest count vs system, with variance
CREATE OR REPLACE VIEW v_count_variance AS
SELECT p.product_code, p.product_name,
       ioh.on_hand AS system_on_hand,
       lc.counted_jars, lc.count_date,
       lc.counted_jars - ioh.on_hand AS variance
FROM product p
JOIN v_inventory_on_hand ioh ON ioh.product_id=p.product_id
LEFT JOIN LATERAL (SELECT counted_jars, count_date FROM inventory_count ic
                   WHERE ic.product_id=p.product_id
                   ORDER BY count_date DESC, count_id DESC LIMIT 1) lc ON TRUE;

-- Dynamic reorder point from recent sales velocity. The demand window comes from
-- business_setting; lead time and safety days come from each product.
CREATE OR REPLACE VIEW v_reorder_suggestion AS
WITH win AS (SELECT CAST(setting_value AS INT) AS days FROM business_setting WHERE setting_key = 'demand_window_days'),
demand AS (
    SELECT si.product_id, SUM(si.quantity)::numeric / (SELECT days FROM win) AS avg_daily
    FROM sale_item si JOIN sale s ON s.sale_id=si.sale_id
    WHERE s.sale_date >= (SELECT MAX(sale_date) FROM sale) - (SELECT days FROM win) * INTERVAL '1 day'
    GROUP BY si.product_id)
SELECT p.product_code, p.product_name,
       ROUND(COALESCE(d.avg_daily,0),1) AS avg_daily_demand,
       p.lead_time_days, p.safety_days,
       CEIL(COALESCE(d.avg_daily,0) * (p.lead_time_days + p.safety_days))::int AS suggested_reorder,
       p.reorder_level AS current_reorder,
       (SELECT days FROM win) AS demand_window_days
FROM product p LEFT JOIN demand d ON d.product_id=p.product_id ORDER BY p.product_id;

