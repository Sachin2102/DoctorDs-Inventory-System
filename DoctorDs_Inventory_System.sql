-- ======================= PART 9: OVERSELL GUARD (concurrency-safe) ==========
CREATE OR REPLACE FUNCTION fn_prevent_oversell() RETURNS TRIGGER AS $$
DECLARE cur_on_hand INT;
BEGIN
    PERFORM pg_advisory_xact_lock(NEW.product_id);
    SELECT COALESCE((SELECT SUM(jars_produced) FROM production_batch     WHERE product_id=NEW.product_id),0)
         + COALESCE((SELECT SUM(quantity)       FROM inventory_adjustment WHERE product_id=NEW.product_id),0)
         - COALESCE((SELECT SUM(quantity)       FROM sale_item            WHERE product_id=NEW.product_id),0)
      INTO cur_on_hand;
    IF NEW.quantity > cur_on_hand THEN
        RAISE EXCEPTION 'Oversell blocked: only % jars in stock for product %', cur_on_hand, NEW.product_id;
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_prevent_oversell ON sale_item;
CREATE TRIGGER trg_prevent_oversell BEFORE INSERT ON sale_item
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_oversell();

